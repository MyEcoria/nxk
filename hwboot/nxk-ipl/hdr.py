#!/usr/bin/env python3
"""Register constants for nxk-ipl, taken from hekate's headers.

    hdr.py [--hekate refs/hekate] -o hwboot/nxk-ipl/src/hdr.rs

Keeps hekate's names, so the Rust port reads like the C it follows: every
`#define NAME <constant expression>` and every `NAME = <constant>` enum
entry of the listed headers whose value is a plain number once BIT() and
the integer suffixes are gone. Anything else (macros with arguments,
casts to pointers, strings) is skipped. The output is committed: the
build does not need refs/.
"""
import argparse
import os
import re

HEADERS = [
    "bdk/soc/t210.h",
    "bdk/soc/bpmp.h",
    "bdk/soc/ccplex.h",
    "bdk/soc/clock.h",
    "bdk/soc/pmc.h",
    "bdk/soc/pmc_t210.h",
    "bdk/soc/fuse.h",
    "bdk/soc/gpio.h",
    "bdk/soc/pinmux.h",
    "bdk/soc/i2c.h",
    "bdk/soc/uart.h",
    "bdk/soc/timer.h",
    "bdk/soc/hw_init.h",
    "bdk/power/max77620.h",
    "bdk/power/max7762x.h",
    "bdk/power/max77812.h",
    "bdk/power/max17050.h",
    "bdk/power/bq24193.h",
    "bdk/mem/mc.h",
    "bdk/mem/mc_t210.h",
    "bdk/mem/emc_t210.h",
    "bdk/mem/sdram.h",
    "bdk/display/di.h",
    "bdk/storage/sdmmc_t210.h",
    "bdk/storage/sdmmc_driver.h",
    "bdk/storage/sdmmc.h",
    "bdk/storage/sd_def.h",
    "bdk/storage/mmc_def.h",
    "bdk/sec/se_t210.h",
]

DEFINE = re.compile(r"^\s*#define\s+([A-Za-z_]\w*)\s+(.+?)\s*(?://.*|/\*.*)?$")
ENUM = re.compile(r"^\s*([A-Za-z_]\w*)\s*=\s*([^,/]+?)\s*,?\s*(?://.*|/\*.*)?$")


def clean(expr, known):
    e = re.sub(r"\bBIT\(", "_BIT(", expr)
    e = re.sub(r"(\b0[xX][0-9a-fA-F]+|\b\d+)[uUlL]+\b", r"\1", e)
    e = re.sub(r"\((?:u8|u16|u32|unsigned int|int)\)", "", e)
    if re.search(r"[\"'?]|->|\.\w", e):
        return None
    for w in set(re.findall(r"\b[A-Za-z_]\w*\b", e)):
        if w == "_BIT":
            continue
        if w not in known:
            return None
        e = re.sub(rf"\b{w}\b", f"({known[w]})", e)
    e = e.replace("&&", " and ").replace("||", " or ")
    try:
        v = eval(e, {"__builtins__": {}}, {"_BIT": lambda n: 1 << n})
    except Exception:
        return None
    return v if isinstance(v, int) else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--hekate", default=os.path.join(os.path.dirname(__file__), "..", "..", "refs", "hekate"))
    ap.add_argument("-o", required=True)
    a = ap.parse_args()
    known, order, seen = {}, [], set()
    for h in HEADERS:
        in_enum = False
        for line in open(os.path.join(a.hekate, h), encoding="utf-8", errors="replace"):
            if re.match(r"^\s*(typedef\s+)?enum\b", line):
                in_enum = True
                continue
            if in_enum and "}" in line:
                in_enum = False
                continue
            m = DEFINE.match(line) or (ENUM.match(line) if in_enum else None)
            if not m:
                continue
            name, expr = m.group(1), m.group(2)
            if "(" in name or name.startswith("_") or name.endswith("_H_"):
                continue
            v = clean(expr, known)
            if v is None:
                continue
            if name in known and known[name] != v:
                print(f"conflict: {name} in {h}, kept the first value")
                continue
            known[name] = v
            if name not in seen:
                seen.add(name)
                order.append((h, name))
    out = ["// Generated by hwboot/nxk-ipl/hdr.py from hekate's headers (GPL-2.0).",
           "// Do not edit: rerun the script.", "#![allow(dead_code)]", ""]
    last = None
    for h, name in order:
        if h != last:
            out.append(f"\n// {h}")
            last = h
        v = known[name]
        ty, v = ("u32", v & 0xFFFF_FFFF) if v >= 0 else ("i32", v)
        out.append(f"pub const {name}: {ty} = {v:#x};" if ty == "u32" else f"pub const {name}: {ty} = {v};")
    open(a.o, "w").write("\n".join(out) + "\n")
    print(f"{len(order)} constants -> {a.o}")


main()
