#!/usr/bin/env python3
"""Display register tables for nxk-ipl, taken from hekate's bdk/display/di.inl.

    digen.py [--hekate refs/hekate] -o hwboot/nxk-ipl/src/di_tables.rs

Every `static const reg_cfg_t NAME[] = { {INDEX, VALUE}, ... }` array as
a Rust table of (u32 word index, value), hekate's names kept (without the
leading underscore). Constants come from hdr.rs's set and the one-argument
macros of di.h. The output is committed: the build does not need refs/.
"""
import argparse
import os
import re


def strip(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument("--hekate", default=os.path.join(here, "..", "..", "refs", "hekate"))
    ap.add_argument("-o", required=True)
    a = ap.parse_args()
    consts = {m.group(1): int(m.group(2), 16) for line in open(os.path.join(here, "src", "hdr.rs"))
              if (m := re.match(r"pub const (\w+): u32 = (0x[0-9a-f]+);", line))}
    di_h = strip(open(os.path.join(a.hekate, "bdk", "display", "di.h")).read()).replace("\\\n", " ")
    macros = {m.group(1): (m.group(2), m.group(3)) for m in
              re.finditer(r"^\s*#define\s+(\w+)\((\w+)\)\s+(.+?)\s*$", di_h, re.M)}

    def expand(e):
        for _ in range(10):
            hit = False
            for name, (arg, body) in macros.items():
                m = re.search(rf"\b{name}\(([^()]*)\)", e)
                if m:
                    e = e[:m.start()] + "(" + re.sub(rf"\b{arg}\b", f"({m.group(1)})", body) + ")" + e[m.end():]
                    hit = True
            if not hit:
                return e
        return e

    def evaluate(expr):
        e = expand(" ".join(expr.split()))
        e = re.sub(r"(\b0[xX][0-9a-fA-F]+|\b\d+)[uUlL]+\b", r"\1", e)
        e = re.sub(r"\bBIT\(", "_BIT(", e)
        for w in set(re.findall(r"\b[A-Za-z_]\w*\b", e)) - {"_BIT"}:
            if w not in consts:
                raise SystemExit(f"unknown constant {w} in {expr!r}")
            e = re.sub(rf"\b{w}\b", str(consts[w]), e)
        return eval(e, {"__builtins__": {}}, {"_BIT": lambda n: 1 << n}) & 0xFFFF_FFFF

    text = strip(open(os.path.join(a.hekate, "bdk", "display", "di.inl")).read())
    out = ["// Generated by hwboot/nxk-ipl/digen.py from hekate's bdk/display/di.inl (GPL-2.0).",
           "// Do not edit: rerun the script. (word index, value) pairs.", "#![allow(dead_code)]", ""]
    n = 0
    for m in re.finditer(r"static const reg_cfg_t _(\w+)\[\]\s*=\s*\{(.*?)\};", text, re.S):
        pairs = re.findall(r"\{\s*([^{},]+?)\s*,\s*([^{}]+?)\s*\}", m.group(2))
        vals = [(evaluate(i), evaluate(v)) for i, v in pairs]
        out.append(f"pub static {m.group(1).upper()}: [(u32, u32); {len(vals)}] = [")
        out += [f"    ({i:#x}, {v:#010x})," for i, v in vals]
        out.append("];")
        n += 1
    open(a.o, "w").write("\n".join(out) + "\n")
    print(f"{n} tables -> {a.o}")


main()
