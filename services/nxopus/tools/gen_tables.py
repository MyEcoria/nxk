#!/usr/bin/env python3
"""Writes src/tables.rs from libopus's float sources (the 48 kHz, 960
sample static mode and the CELT tables), so no value is typed by hand.

    python3 services/nxopus/tools/gen_tables.py OPUS_SRC > services/nxopus/src/tables.rs

OPUS_SRC: the libopus tree (e.g. opusic-sys-0.7.5/opus in ~/.cargo/registry).
"""
import re, sys

src = sys.argv[1]


def read(path):
    text = open(f"{src}/{path}").read()
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def array(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*(\[[^=]*\])\s*=\s*\{", text)
    if not m:
        raise SystemExit(f"{name} not found")
    depth, i = 1, m.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    body = text[m.end():i - 1]
    return [v for v in re.findall(r"-?[0-9][0-9.e+-]*f?", body)]


def num(v, ty):
    v = v.rstrip("f")
    if ty == "f32":
        return v if ("." in v or "e" in v) else v + ".0"
    return v


def emit(name, ty, values, per=12):
    vals = [num(v, ty) for v in values]
    print(f"pub static {name}: [{ty}; {len(vals)}] = [")
    for k in range(0, len(vals), per):
        print("    " + ", ".join(vals[k:k + per]) + ",")
    print("];\n")


modes = read("celt/static_modes_float.h")
mainc = read("celt/modes.c")
qb = read("celt/quant_bands.c")
qb_float = qb[qb.index("#else", qb.index("eMeans")):]

print("// Generated by tools/gen_tables.py from libopus 1.6.1 (BSD-3-Clause,")
print("// see LICENSE in this crate). Do not edit.")
print("#![allow(clippy::all)]\n")
emit("EBANDS", "i16", array(mainc, "eband5ms"))
emit("BAND_ALLOCATION", "u8", array(mainc, "band_allocation"), 21)
emit("WINDOW", "f32", array(modes, "window120"), 6)
emit("LOGN", "i16", array(modes, "logN400"))
emit("CACHE_INDEX", "i16", array(modes, "cache_index50"))
emit("CACHE_BITS", "u8", array(modes, "cache_bits50"), 16)
emit("CACHE_CAPS", "u8", array(modes, "cache_caps50"), 16)
emit("FFT_TWIDDLES", "f32", array(modes, "fft_twiddles48000_960"), 8)
for n in (480, 240, 120, 60):
    emit(f"FFT_BITREV{n}", "i16", array(modes, f"fft_bitrev{n}"), 16)
emit("MDCT_TWIDDLES", "f32", array(modes, "mdct_twiddles960"), 6)
emit("E_MEANS", "f32", array(qb_float, "eMeans"), 5)
emit("E_PROB_MODEL", "u8", array(qb, "e_prob_model"), 14)
