#!/usr/bin/env python3
"""Generate emc/src/regs.rs and emc/src/layout.rs from hekate's Minerva sources.

    tools/mkemctab.py HEKATE_DIR [TABLES_DIR]

HEKATE_DIR is a hekate checkout (refs/hekate): the register names come from
modules/hekate_libsys_minerva/mtc_mc_emc_regs.h, the address tables from
sys_sdrammtc.c, the table layout (word offsets) from mtc_table.h. The output
is committed; refs/ itself is never compiled (AGENTS.md section 6).
"""
import re
import sys
from pathlib import Path

HDR = """// Generated by tools/mkemctab.py from hekate's Minerva
// (modules/hekate_libsys_minerva, GPL-2, (c) 2018-2025 CTCaer / NVIDIA).
// Do not edit by hand.
"""


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return re.sub(r"//[^\n]*", "", s)


def parse_defines(text):
    """Name -> int for every `#define NAME <constant expression>`."""
    defs = {}
    for line in strip_comments(text).splitlines():
        m = re.match(r"\s*#define\s+(\w+)\s+(.+?)\s*$", line)
        if not m:
            continue
        name, expr = m.groups()
        expr = re.sub(r"BIT\((\d+)\)", r"(1<<\1)", expr)
        expr = re.sub(r"\b(0x[0-9A-Fa-f]+|\d+)[uU]\b", r"\1", expr)
        if not re.fullmatch(r"[\w\s()<>|&+\-x]*", expr):
            continue
        try:
            defs[name] = eval(expr, {"__builtins__": {}}, dict(defs))
        except Exception:
            pass
    return defs


def parse_tables(text, defs):
    """Name -> list of ints for `static const u32 name[N] = { ids };`."""
    out = {}
    for m in re.finditer(
        r"static const u32 (\w+)\[(\w+)\]\s*=\s*\{(.*?)\};", strip_comments(text), re.S
    ):
        name, count, body = m.groups()
        if name.startswith("ram_pattern"):
            continue  # patterns.rs
        items = [x.strip() for x in body.split(",") if x.strip()]
        vals = [defs[i] if i in defs else int(i, 0) for i in items]
        n = int(count, 0) if count.isdigit() or count.startswith("0x") else len(vals)
        assert len(vals) == n, (name, len(vals), n)
        out[name] = vals
    return out


def parse_pllm(text):
    m = re.search(r"pllm_clk_config_table\[\]\s*=\s*\{(.*?)\n\};", strip_comments(text), re.S)
    rows = re.findall(r"\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", m.group(1))
    return [tuple(int(x) for x in r) for r in rows if int(r[0])]


def parse_structs(text):
    """Struct name -> [(field, kind, count)] where kind is 'u32', 'char' or a struct."""
    structs = {}
    for m in re.finditer(r"typedef struct\s*\{(.*?)\}\s*(\w+);", strip_comments(text), re.S):
        body, name = m.groups()
        fields = []
        for fm in re.finditer(r"(\w+)\s+(\w+)(?:\[(\d+)\])?\s*;", body):
            kind, fname, cnt = fm.groups()
            fields.append((fname, kind, int(cnt) if cnt else 1))
        structs[name] = fields
    return structs


def layout(structs, name, prefix, base, out):
    """Append (CONST, word offset) for every field; nested structs recurse."""
    off = base
    for fname, kind, cnt in structs[name]:
        const = (prefix + fname).upper()
        if kind == "u32":
            out.append((const, off, cnt))
            off += cnt
        elif kind == "char":
            assert cnt % 4 == 0
            out.append((const, off, cnt // 4))
            off += cnt // 4
        else:
            off = layout(structs, kind, const + "_", off, out) if cnt == 1 else None
    return off


def main():
    root = Path(sys.argv[1]) / "modules" / "hekate_libsys_minerva"
    here = Path(__file__).resolve().parent.parent / "emc" / "src"
    regs = (root / "mtc_mc_emc_regs.h").read_text()
    seq = (root / "sys_sdrammtc.c").read_text()
    tbl = (root / "mtc_table.h").read_text()

    defs = parse_defines(regs)
    tables = parse_tables(seq, defs)
    with open(here / "regs.rs", "w") as f:
        f.write(HDR)
        f.write("//! Register offsets and address tables of the EMC sequence.\n\n")
        f.write("#![allow(dead_code)]\n\n")
        for k, v in defs.items():
            if k.startswith("_") or k in ("BIT",):
                continue
            f.write(f"pub const {k}: u32 = {v:#x};\n")
        f.write("\n")
        for k, v in tables.items():
            f.write(f"pub static {k.upper()}: [u32; {len(v)}] = [\n")
            for i in range(0, len(v), 8):
                f.write("    " + ", ".join(f"{x:#x}" for x in v[i : i + 8]) + ",\n")
            f.write("];\n")
        f.write("\n/// (input MHz*1000, output kHz, feedback n, input m, post p) rows.\n")
        rows = parse_pllm(seq)
        f.write(f"pub static PLLM_CONFIG: [[u32; 5]; {len(rows)}] = [\n")
        for r in rows:
            f.write("    [" + ", ".join(str(x) for x in r) + "],\n")
        f.write("];\n")

    structs = parse_structs(tbl)
    out = []
    end = layout(structs, "emc_table_t", "", 0, out)
    with open(here / "layout.rs", "w") as f:
        f.write(HDR)
        f.write("//! Word offsets of `emc_table_t` (rev 7, 4928 bytes) fields.\n\n")
        f.write("#![allow(dead_code)]\n\n")
        f.write(f"pub const TABLE_WORDS: usize = {end};\n")
        for const, off, cnt in out:
            f.write(f"pub const {const}: usize = {off};\n")
            if cnt > 1:
                f.write(f"pub const {const}_LEN: usize = {cnt};\n")

    # RAM training patterns (the tables Minerva loads into EMC_TRAINING_PATRAM).
    with open(here / "patterns.rs", "w") as f:
        f.write(HDR)
        f.write("//! RAM patterns for the DQ and DMI training (256 words per pattern).\n\n")
        for m in re.finditer(
            r"static const u32 (ram_pattern_\w+)\[(\w+)\]\s*=\s*\{(.*?)\};", strip_comments(seq), re.S
        ):
            vals = [int(x.strip(), 0) for x in m.group(3).split(",") if x.strip()]
            assert len(vals) == int(m.group(2), 0), m.group(1)
            f.write(f"pub static {m.group(1).upper()}: [u32; {len(vals)}] = [\n")
            for i in range(0, len(vals), 8):
                f.write("    " + ", ".join(f"{x:#010x}" for x in vals[i : i + 8]) + ",\n")
            f.write("];\n")

    # ODINX02 base tables (7 entries of 4928 bytes) as raw files, for the
    # card (nxk-ipl reads the one its DRAM id needs).
    if len(sys.argv) > 2:
        out = Path(sys.argv[2])
        out.mkdir(parents=True, exist_ok=True)
        sw = strip_comments((root / "mtc_switch_tables.h").read_text())
        for m in re.finditer(r"static const unsigned char (odinx02_a2_(\d+)\w*?)\[\w+\]\s*=\s*\{(.*?)\};", sw, re.S):
            data = bytes(int(x.strip(), 0) for x in m.group(3).split(",") if x.strip())
            assert len(data) == 7 * 4928, (m.group(1), len(data))
            (out / f"odinx02_{m.group(2)}.bin").write_bytes(data)


main()
